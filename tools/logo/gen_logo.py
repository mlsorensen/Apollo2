#!/usr/bin/env python3
"""Regenerate include/ui/img_lion.h from la-marzocco-lion.svg.

The screensaver's bouncing lion is an LVGL A8 alpha map (shape only, recolored
at draw time — which is also what makes it the "inverted" light-on-dark logo).
The header is COMMITTED because rasterizing needs rsvg-convert (brew install
librsvg); re-run this only when the artwork changes:

    python3 tools/logo/gen_logo.py

Do NOT substitute qlmanage: its thumbnails squash the tall artwork square
(that shipped once — a visibly cut-off lion).
"""

import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SVG = HERE / "la-marzocco-lion.svg"
OUT = HERE.parent.parent / "include/ui/img_lion.h"
WIDTH = 160  # tallest use is ~45% of an 800px-tall screen; LVGL scales down


def main():
    with tempfile.TemporaryDirectory() as td:
        png = Path(td) / "lion.png"
        subprocess.run(
            ["rsvg-convert", "--height", "1024", "--keep-aspect-ratio",
             "-o", str(png), str(SVG)],
            check=True, capture_output=True)
        im = Image.open(png).convert("RGBA")
    # Alpha map: use the alpha channel when present, else treat dark-on-light.
    a = im.getchannel("A")
    if a.getextrema() == (255, 255):  # opaque render: shape is the dark ink
        a = Image.eval(im.convert("L"), lambda v: 255 - v)
    # Crop to content, then scale to the target width.
    bbox = a.getbbox()
    a = a.crop(bbox)
    h = round(a.height * WIDTH / a.width)
    a = a.resize((WIDTH, h), Image.LANCZOS)
    data = a.tobytes()

    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/logo/gen_logo.py from tools/logo/la-marzocco-lion.svg",
        "// (committed: regeneration needs macOS qlmanage). A8 alpha map of the lion,",
        "// recolored at draw time by the screensaver.",
        "",
        '#include "lvgl.h"',
        "",
        "namespace ui {",
        "",
        f"inline constexpr int kLionW = {WIDTH};",
        f"inline constexpr int kLionH = {h};",
        "",
        f"inline const uint8_t kLionMap[{WIDTH * h}] = {{",
    ]
    for i in range(0, len(data), 24):
        chunk = ",".join(str(b) for b in data[i:i + 24])
        lines.append(f"  {chunk},")
    lines += [
        "};",
        "",
        "// Runtime-built descriptor (avoids nested designated initializers, which",
        "// C++ rejects and LVGL's struct layout makes brittle to hardcode).",
        "inline const lv_image_dsc_t* lion_logo() {",
        "  static lv_image_dsc_t dsc;",
        "  static bool ready = false;",
        "  if (!ready) {",
        "    dsc.header.magic = LV_IMAGE_HEADER_MAGIC;",
        "    dsc.header.cf = LV_COLOR_FORMAT_A8;",
        "    dsc.header.w = kLionW;",
        "    dsc.header.h = kLionH;",
        "    dsc.header.stride = kLionW;",
        "    dsc.data_size = sizeof(kLionMap);",
        "    dsc.data = kLionMap;",
        "    ready = true;",
        "  }",
        "  return &dsc;",
        "}",
        "",
        "}  // namespace ui",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({WIDTH}x{h}, {len(data)} bytes)")


if __name__ == "__main__":
    main()
